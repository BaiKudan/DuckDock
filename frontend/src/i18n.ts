function format(template: string, vars?: Record<string, string | number>) {
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));
}

export function useI18n() {
  const locale = useI18nStore((state) => state.locale);
  const setLocale = useI18nStore((state) => state.setLocale);

  return {
    locale,
    setLocale,
    t: (key: string, vars?: Record<string, string | number>) => {
      const current = messages[locale] as Record<string, string>;
      const fallback = messages.en as Record<string, string>;
      return format(current[key] ?? fallback[key] ?? key, vars);
    },
  };
}

export function formatDate(locale: Locale, value: string) {
  return new Date(value).toLocaleDateString(locale === "zh" ? "zh-CN" : "en-US");
}
